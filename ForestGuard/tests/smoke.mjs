import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const root=new URL('../',import.meta.url);
const read=name=>readFileSync(new URL(name,root),'utf8');
const html=read('index.html'),css=read('style.css'),js=read('game.js');
execFileSync(process.execPath,['--check',new URL('game.js',root).pathname]);
assert.match(html,/lang="ko"/);
assert.match(html,/viewport-fit=cover/);
assert.match(html,/id="game-root"/);
assert.match(html,/id="stage-grid"/);
assert.match(html,/id="skill-btn"/);
assert.match(css,/100dvh/);
assert.match(css,/\[hidden\]\{display:none!important\}/);
assert.match(js,/class WaveDirector/);
assert.match(js,/class ForestBattle/);
assert.match(js,/this\.enemies/);
assert.match(js,/this\.projectiles/);
assert.match(js,/this\.showDraft/);
assert.match(js,/localStorage/);
assert.match(js,/popstate/);
assert.match(js,/const STAGES = \[/);
assert.match(js,/const CARDS = \[/);
assert.doesNotMatch(html+css+js,/<svg\b|data:image\/svg\+xml|\.svg(?:["'(])/i);
assert.doesNotMatch(js,/eval\s*\(/);
console.log('ForestGuard v0.1 smoke: PASS (syntax, core wiring, safe UI conventions).');