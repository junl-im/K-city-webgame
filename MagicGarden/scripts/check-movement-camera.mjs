import assert from 'node:assert/strict';
import { advanceMovement, smoothFollow, calculateCameraTarget } from '../src/movement-camera.ts';
const approx = (a, b, tolerance = .001) => assert.ok(Math.abs(a - b) < tolerance, `${a} !== ${b}`);
const still = advanceMovement(10, 20, 10, 20, 16.67);
assert.deepEqual(still, { x: 10, y: 20, traveled: 0 });
assert.equal(advanceMovement(10, 20, 11, 21, 16.67).x, 11);
assert.equal(advanceMovement(10, 20, 11, 21, 16.67).y, 21);
const east = advanceMovement(10, 20, 500, 20, 16.667);
approx(east.traveled, 3.5);
approx(east.y, 20);
const west = advanceMovement(30, 20, -300, 20, 16.667);
assert.ok(west.x < 30);
const diagonal = advanceMovement(0, 0, 100, 100, 16.667);
approx(diagonal.x, diagonal.y);
assert.ok(diagonal.traveled > 0 && diagonal.traveled <= 3.5);
const near = advanceMovement(0, 0, 7, 0, 16.667);
assert.ok(near.traveled < east.traveled);
const fast = advanceMovement(0, 0, 300, 0, 10000);
assert.ok(fast.traveled <= 3.5 * 2.4 + .001);
assert.deepEqual(advanceMovement(1, 1, 50, 50, 0), { x: 1, y: 1, traveled: 0 });
approx(smoothFollow(0, 100, 120), 50);
assert.ok(smoothFollow(10, 20, 16.667) > 10);
assert.ok(smoothFollow(10, 20, 16.667) < 20);
assert.equal(smoothFollow(10, 10.2, 16.667), 10.2);
assert.equal(smoothFollow(10, 20, 0), 10);
const wide = calculateCameraTarget(1440, 900, 1280, 800, 640, 580);
approx(wide.scale, 1.125);
approx(wide.x, 0);
approx(wide.y, 0);
const portrait = calculateCameraTarget(390, 844, 1280, 800, 640, 580);
assert.ok(portrait.scale > 0 && portrait.x <= 0 && portrait.y <= 0);
assert.ok(portrait.x >= 390 - 1280 * portrait.scale);
assert.ok(portrait.y >= 844 - 800 * portrait.scale);
const border = calculateCameraTarget(320, 800, 1280, 800, 1280, 800);
assert.ok(border.x <= 0 && border.x >= 320 - 1280 * border.scale - .001);
console.log('Movement and camera checks passed (20 cases).');
